import { describe, expect, it } from "vitest";
import { codeLines, DEFAULT_CONFIG, longFiles, resolveConfig } from "../../src";

/** `count` lines of code, in no language in particular. */
const lines = (count: number): string =>
  Array.from({ length: count }, (_, index) => `value_${index} = ${index}`).join("\n");

describe("codeLines", () => {
  it("leaves out blank lines and comments, whatever the language", () => {
    const text = [
      "// line comment",
      "# line comment",
      "-- line comment",
      "--",
      "/* block",
      " * comment */",
      "<!-- block",
      "comment -->",
      "--[[ block",
      "comment ]]",
      "/** one-line block */",
      "#!/usr/bin/env node",
      "",
      "   ",
      "code()",
    ].join("\n");
    expect(codeLines(text)).toBe(1);
  });

  it("counts what only looks like a comment in some languages", () => {
    const text = [
      "#include <stdio.h>",
      "#define MAX 10",
      "#ifdef DEBUG",
      "#endif",
      "#pragma once",
      "#region Helpers",
      "#[derive(Debug)]",
      "#![allow(unused)]",
      "#app {",
      "#main-nav a,",
      "#title { color: red; }",
      "--i;",
    ].join("\n");
    expect(codeLines(text)).toBe(12);
    // A comment that only starts like a directive stays a comment.
    expect(codeLines("# if the cache is cold\n# define the order first")).toBe(0);
  });
});

describe("longFiles", () => {
  const sized = (path: string, after: string, before?: string) => ({
    path,
    after,
    ...(before !== undefined ? { before } : {}),
  });

  it("warns when the task grows a file past 300 lines of code, and blocks past 500", () => {
    expect(
      longFiles(
        [
          sized("src/a.ts", lines(320), lines(250)),
          sized("src/b.py", lines(520)),
          sized("src/c.go", lines(310), lines(310)),
          sized("src/d.rs", lines(530), lines(510)),
        ],
        DEFAULT_CONFIG,
      ),
    ).toEqual([
      { path: "src/a.ts", lines: 320, before: 250, limit: 300, severity: "warning" },
      { path: "src/b.py", lines: 520, before: 0, limit: 500, severity: "error" },
      { path: "src/d.rs", lines: 530, before: 510, limit: 300, severity: "warning" },
    ]);
  });

  it("gives tests more room", () => {
    const files = [sized("test/a_test.go", lines(450)), sized("src/b.test.ts", lines(610))];
    expect(longFiles(files, DEFAULT_CONFIG).map((file) => [file.limit, file.severity])).toEqual([
      [400, "warning"],
      [600, "error"],
    ]);
  });

  it("never blocks with fail: false, and follows the person's thresholds", () => {
    const resolved = resolveConfig({ version: 1, lines: { warn: 100, fail: false } });
    if (!resolved.ok) throw new Error("invalid config");
    expect(longFiles([sized("src/a.ts", lines(900))], resolved.config)).toEqual([
      { path: "src/a.ts", lines: 900, before: 0, limit: 100, severity: "warning" },
    ]);
  });

  it("does not size what is not hand-written code", () => {
    const big = lines(900);
    const config = {
      ...DEFAULT_CONFIG,
      scope: { ...DEFAULT_CONFIG.scope, generated: ["**/*.pb.*"] },
    };
    expect(
      longFiles(
        [
          sized("docs/guide.md", big),
          sized("api/user.pb.go", big),
          sized("src/client.ts", `// Code generated by a tool. DO NOT EDIT.\n${big}`),
          sized("src/schema.py", `# @generated\n${big}`),
          sized("pnpm-lock.yaml", big),
          sized("Cargo.lock", big),
          sized("assets/logo.bin", `\0${big}`),
          sized("db/migrations/0001.sql", big),
          sized("src/locales/es.json", big),
          sized("test/fixtures/data.json", big),
          sized(".specty/changes/x/spec.md", big),
        ],
        config,
      ),
    ).toEqual([]);
  });
});

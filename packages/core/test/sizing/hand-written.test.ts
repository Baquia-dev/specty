import { describe, expect, it } from "vitest";
import { computeSize, DEFAULT_CONFIG, fileSize, isGeneratedText } from "../../src";
import { check, fixture, specOf, withConfig } from "../helpers";

/** The standard example: 3 files in 2 modules, a score of 5 (M). */
const STANDARD = fixture("standard.es.md");

/** The standard example with more entries in its Files section. */
const withFiles = (...entries: string[]): string =>
  STANDARD.replace(
    "\n## Tareas",
    `${entries.map((entry) => `- ${entry}`).join("\n")}\n\n## Tareas`,
  );

const paths = (count: number, path: (index: number) => string): string[] =>
  Array.from({ length: count }, (_, index) => path(index));

describe("the size counts only hand-written code", () => {
  it("leaves out the matches of a glob over an ignored folder", () => {
    // The change that got stuck: Flutter's launcher icons, in a folder Specty ignores.
    const glob = "android/app/src/main/res/**";
    const text = withFiles(`modificar ${glob} — iconos generados`);
    const config = withConfig({ ignored: [...DEFAULT_CONFIG.ignored, "android/**", "ios/**"] });
    const icons = paths(70, (index) => `android/app/src/main/res/mipmap-${index}/ic_launcher.xml`);
    const size = computeSize(specOf(text), config, { globMatches: { [glob]: icons } });
    expect(size.signals.fileCount).toBe(3);
    expect(size.signals.files).toEqual({ create: 1, modify: 2, delete: 0, rename: 0 });
    expect(size.signals.codeFiles).toBe(2);
    expect(size).toMatchObject({ level: "M", score: 5 });
  });

  it("leaves out explicit paths that are not governed, such as documentation", () => {
    const text = withFiles(
      "modificar docs/ARCHITECTURE.md — diseño",
      "modificar lib/README.md — uso",
    );
    const size = computeSize(specOf(text), DEFAULT_CONFIG);
    expect(size.signals.fileCount).toBe(3);
    expect(size.score).toBe(5);
  });

  it("leaves out what scope.generated names, listed or matched", () => {
    const glob = "lib/**/*.g.dart";
    const text = withFiles(
      `modificar ${glob} — serialización`,
      "crear lib/features/home/home_state.freezed.dart — estado",
    );
    const config = withConfig({
      scope: { ...DEFAULT_CONFIG.scope, generated: ["**/*.g.dart", "**/*.freezed.dart"] },
    });
    const models = paths(40, (index) => `lib/models/model_${index}.g.dart`);
    const size = computeSize(specOf(text), config, { globMatches: { [glob]: models } });
    expect(size.signals.fileCount).toBe(3);
    expect(size.signals.codeFiles).toBe(2);
    expect(size.signals.modules).toEqual(["analytics", "home"]);
    expect(size.score).toBe(5);
  });

  it("leaves out lockfiles and what the CLI found generated or binary", () => {
    const glob = "public/assets/**";
    const text = withFiles(
      "modificar pubspec.lock — dependencias",
      "modificar db/schema.rb — esquema",
      "crear proto/user_pb2.py — mensajes",
      "crear api/user.pb.go — mensajes",
      `modificar ${glob} — imágenes`,
    );
    const images = paths(30, (index) => `public/assets/image-${index}.png`);
    const generated = ["db/schema.rb", "proto/user_pb2.py", "api/user.pb.go", ...images];
    const size = computeSize(specOf(text), DEFAULT_CONFIG, {
      globMatches: { [glob]: images },
      generated,
    });
    // The glob itself still counts one, as a glob without matches does.
    expect(size.signals.fileCount).toBe(4);
    expect(size.signals.codeFiles).toBe(3);
    expect(size.signals.modules).toEqual(["analytics", "home", "public"]);
  });

  it("keeps counting every match of a glob over hand-written code, and an XL needs an epic", () => {
    const glob = "lib/features/home/**";
    const text = withFiles(`modificar ${glob} — vista`);
    const pages = paths(20, (index) => `lib/features/home/page_${index}.dart`);
    const repo = { globMatches: { [glob]: pages } };
    const size = computeSize(specOf(text), DEFAULT_CONFIG, repo);
    expect(size.signals.fileCount).toBe(24);
    expect(size.signals.codeFiles).toBe(23);
    expect(size.level).toBe("XL");
    expect(check(text, { repo })).toContain("split-required");
  });
});

describe("isGeneratedText", () => {
  it("recognizes the marks generators write at the top", () => {
    const heads = [
      "// GENERATED CODE - DO NOT MODIFY BY HAND\n\npart of 'user.dart';\n",
      "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
      "// Code generated by protoc-gen-go. DO NOT EDIT.\n",
      "# This file is auto-generated from the current state of the database.\n",
      "/**\n * NOTE: This class is auto generated by OpenAPI Generator.\n */\n",
      "/* @generated */\nexport const a = 1;\n",
    ];
    for (const head of heads) expect(isGeneratedText(head), head).toBe(true);
  });

  it("recognizes binaries and leaves hand-written code alone", () => {
    expect(isGeneratedText("\x89PNG\r\n\x1a\n\0\0\0\rIHDR")).toBe(true);
    expect(isGeneratedText("export const greet = () => 'hola';\n")).toBe(false);
    // A mark past the first lines is not a header.
    const late = `${"const a = 1;\n".repeat(10)}// DO NOT EDIT\n`;
    expect(isGeneratedText(late)).toBe(false);
  });

  it("is the rule max-lines follows too", () => {
    const text = `// GENERATED CODE - DO NOT MODIFY BY HAND\n${"final a = 1;\n".repeat(900)}`;
    expect(fileSize("lib/models/user.g.dart", text, DEFAULT_CONFIG)).toBeUndefined();
  });
});

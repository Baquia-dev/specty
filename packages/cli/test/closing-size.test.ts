import { describe, expect, it } from "vitest";
import {
  APP,
  CONFIG,
  cli,
  inWorktree,
  person,
  read,
  SPEC,
  SPEC_PATH,
  stateIn,
  writeFiles,
} from "./support";

/** SPEC with one more entry in Files, which its first task also touches. */
function specWith(glob: string, why: string): string {
  return SPEC.replace(
    "- crear src/app.test.ts — prueba\n",
    `$&- modificar ${glob} — ${why}\n`,
  ).replace(
    "  - files: src/app.ts, src/app.test.ts\n",
    `  - files: src/app.ts, src/app.test.ts, ${glob}\n`,
  );
}

/** `count` files named by `path`, all with `text`. */
function many(count: number, path: (index: number) => string, text: string) {
  return Object.fromEntries(Array.from({ length: count }, (_, index) => [path(index), text]));
}

/**
 * Takes `spec` through its approval and its tasks, the first one writing `written` too, then
 * proposes its closing and closes it: the closing keeps the size of the approval.
 */
async function closeGrown(folder: string, spec: string, written: Record<string, string>) {
  await writeFiles(folder, { [SPEC_PATH]: spec });
  expect((await cli(folder, ["propose"])).code).toBe(0);
  const approved = await cli(folder, ["approve"], { terminal: person({ choose: ["confirm"] }) });
  expect(approved.code).toBe(0);
  const { size } = await stateIn(folder);
  await cli(folder, ["next"]);
  await writeFiles(folder, { "src/app.ts": "1\n", ...written });
  expect((await cli(folder, ["task", "done", "T1", "--summary", "Uno"])).code).toBe(0);
  await writeFiles(folder, { "src/app.ts": "2\n" });
  expect((await cli(folder, ["task", "done", "T2", "--summary", "Dos"])).code).toBe(0);
  expect((await cli(folder, ["accept"], { terminal: person() })).code).toBe(0);
  const closing = "\n## Cierre\n\n### Resumen\n\nSaludo listo.\n";
  await writeFiles(folder, { [SPEC_PATH]: `${await read(folder, SPEC_PATH)}${closing}` });
  const proposed = await cli(folder, ["propose"]);
  expect(proposed.out).toContain("Cierre válido.");
  expect(proposed.out).not.toMatch(/dividir|split/i);
  expect((await stateIn(folder)).size).toEqual(size);
  const closed = await cli(folder, ["close"], { terminal: person() });
  expect(closed.code).toBe(0);
  expect(closed.out).toContain("Incorporado a main.");
}

describe("the size in the closing", () => {
  it("closes a change whose glob filled an ignored folder with generated files (AC4)", async () => {
    // The change that got stuck: launcher icons in a folder Specty ignores.
    const { folder } = await inWorktree({
      ...APP,
      ".specty/config.yaml": `${CONFIG()}ignored: ["**/*.md", "res/**"]\n`,
      "res/mipmap/ic_launcher.xml": "<adaptive-icon/>\n",
    });
    const icons = many(70, (index) => `res/mipmap-${index}/ic_launcher.xml`, "<adaptive-icon/>\n");
    await closeGrown(folder, specWith("res/**", "iconos generados"), icons);
  });

  it("closes a change whose glob over hand-written code grew it to XL (AC5)", async () => {
    const { folder } = await inWorktree();
    const views = many(25, (index) => `src/view_${index}.ts`, "export const view = 1;\n");
    await closeGrown(folder, specWith("src/**", "vistas"), views);
  });
});

describe("the size of what is generated", () => {
  it("leaves out the matches whose content is generated or binary (AC1)", async () => {
    const png = "\x89PNG\r\n\x1a\n\0\0\0\rIHDR";
    const client = "// Code generated by openapi-generator. DO NOT EDIT.\nexport const a = 1;\n";
    const { folder } = await inWorktree({
      ...APP,
      ...many(20, (index) => `src/generated/icon_${index}.png`, png),
      ...many(20, (index) => `src/generated/api_${index}.ts`, client),
    });
    await writeFiles(folder, { [SPEC_PATH]: specWith("src/generated/**", "cliente y recursos") });
    const proposed = await cli(folder, ["propose"]);
    expect(proposed.code).toBe(0);
    expect(proposed.out).toContain("SPEC VÁLIDA · tamaño M (3 archivos, 2 módulos)");
  });
});
